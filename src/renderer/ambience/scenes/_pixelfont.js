const W = 5;
const H = 7;

/** Keep what the font can draw, uppercased, at most `max` characters. */
function sanitizeSign(text, max = 8) {
  return String(text || '').toUpperCase().split('').filter((c) => c === ' ' || GLYPHS[c]).join('').slice(0, max);
}

/**
 * Call `plot(x, y)` for every lit pixel of `text`, laid out horizontally
 * (1 px between letters) or vertically (1 px between rows).
 */
function forEachPixel(text, x0, y0, vertical, plot) {
  let cx = x0;
  let cy = y0;
  for (const ch of String(text)) {
    const rows = GLYPHS[ch];
    if (rows) {
      for (let r = 0; r < H; r++) {
        for (let c = 0; c < W; c++) if (rows[r][c] === '1') plot(cx + c, cy + r);
      }
    }
    if (vertical) cy += H + 1; else cx += W + 1;
  }
}

function measure(text, vertical) {
  const n = String(text).length;
  return vertical ? { w: W, h: n ? n * (H + 1) - 1 : 0 } : { w: n ? n * (W + 1) - 1 : 0, h: H };
}

module.exports = { GLYPHS, GLYPH_W: W, GLYPH_H: H, sanitizeSign, forEachPixel, measure };
